/** The `{ok, code, data}` result of a command that succeeded. */
export function accept(code, data = {}) {
  return Object.freeze({ ok: true, code, data: Object.freeze({ ...data }) });
}

/** The `{ok, code, data}` result of a command that was refused or failed. */
export function refuse(code, data = {}) {
  return Object.freeze({ ok: false, code, data: Object.freeze({ ...data }) });
}
